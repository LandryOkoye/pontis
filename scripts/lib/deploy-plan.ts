// What to deploy where, and the deployments record (BuildPlan B8).

import { tokenAccount } from "./catalogue.ts";
import { BASE_CATALOGUE, type CatalogueData } from "./catalogue-tiers.ts";
import { REPO_ROOT } from "./evidence.ts";

const NEAR = 10n ** 24n;

/** NEAR to give a contract account: 0.01 NEAR per stored byte of code, plus 1 NEAR for state and gas. */
export function fundingFor(codeBytes: number): bigint {
  return BigInt(codeBytes) * 10n ** 19n + NEAR;
}

export interface Target {
  /** Name in the deployment record. */
  readonly label: string;
  readonly accountId: string;
  readonly wasm: string;
  readonly ownerView: string;
  readonly init: Record<string, unknown>;
}

function tokenInit(deployerId: string, name: string, symbol: string, decimals: number) {
  return {
    owner_id: deployerId,
    name,
    symbol,
    decimals,
    faucet_max_per_call: null,
    faucet_cooldown_ms: null,
  };
}

export function targets(deployerId: string, ids: { core: string; a: string; b: string }): Target[] {
  const token = (name: string, symbol: string, decimals: number) =>
    tokenInit(deployerId, name, symbol, decimals);
  return [
    {
      label: "pontis-core",
      accountId: ids.core,
      wasm: "pontis_core",
      ownerView: "get_owner",
      init: { owner_id: deployerId },
    },
    {
      label: "TGOLD-A",
      accountId: ids.a,
      wasm: "synthetic_token",
      ownerView: "owner_id",
      init: token("SYNTHETIC TEST Gold A", "TGOLD-A", 6),
    },
    {
      label: "TGOLD-B",
      accountId: ids.b,
      wasm: "synthetic_token",
      ownerView: "owner_id",
      init: token("SYNTHETIC TEST Gold B", "TGOLD-B", 8),
    },
  ];
}

/**
 * One `synthetic-token` per representation of `data`, on `<representation id>.<deployer>`: the
 * phase 1 catalogue unless a tier's data (catalogue-tiers.ts) is given.
 */
export function catalogueTargets(
  deployerId: string,
  data: CatalogueData = BASE_CATALOGUE,
): Target[] {
  return data.representations.map((rep) => ({
    label: rep.symbol,
    accountId: tokenAccount(rep.id, deployerId),
    wasm: "synthetic_token",
    ownerView: "owner_id",
    init: tokenInit(deployerId, rep.name, rep.symbol, rep.decimals),
  }));
}

export function wasmPath(name: string, env: NodeJS.ProcessEnv = process.env): string {
  const dir = env.PONTIS_WASM_DIR || `${REPO_ROOT}/target/near`;
  return `${dir}/${name}/${name}.wasm`;
}

export function renderDeployments(args: {
  networkId: string;
  deployerId: string;
  rows: { label: string; accountId: string; codeHash: string }[];
  date: string;
}): string {
  const table = args.rows
    .map((r) => `| ${r.label} | \`${r.accountId}\` | \`${r.codeHash}\` |`)
    .join("\n");
  return `# Deployment record

Generated by \`pnpm --filter @pontis/scripts deploy-testnet\`. Testnet and synthetic assets only.

- **Network:** ${args.networkId}
- **Owner and deployer:** \`${args.deployerId}\`
- **Last deployed:** ${args.date}

| Contract | Account | wasm sha256 |
| --- | --- | --- |
${table}

How to reproduce it is in [deployments.md](deployments.md). The quote-signer key is not recorded here; it lives only in the API environment.
`;
}
